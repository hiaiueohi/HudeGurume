(async () => {
  const $ = selector => document.querySelector(selector);
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const count = () => $('#list').children.length;
  const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
  const waitFor = async predicate => { for (let n = 0; n < 100; n++) { if (predicate()) return; await sleep(20); } throw Error('UI update timed out'); };
  assert(count() === 0 && !$('#emptyState').hidden, 'Empty address book should show guidance');
  assert($('#print').disabled, 'Print should be disabled without recipients');
  assert(getComputedStyle($('#import')).display === 'none', 'File input should stay hidden');
  $('#add').click();
  assert($('#recipientDialog').open, 'Individual add should open the editor');
  const form = $('#recipient');
  form.elements.name.value = '山田 太郎';
  form.elements.zip.value = '123-4567';
  form.elements.address.value = '東京都千代田区丸の内1-2-3';
  form.requestSubmit();
  assert(!$('#recipientDialog').open && count() === 1, 'Saving should add a recipient and close the editor');
  assert($('#printCount').textContent === '1', 'New recipient should be selected for printing');
  $('#openImport').click();
  const csv = '氏名,敬称,郵便番号,住所,建物名\n佐藤 花子,様,234-5678,神奈川県横浜市中区1-2,\n鈴木 一郎,様,345-6789,大阪府大阪市北区3-4,○○マンション101号室';
  function chooseFile(text) {
    const transfer = new DataTransfer();
    transfer.items.add(new File([text], '住所録.csv', {type:'text/csv'}));
    $('#import').files = transfer.files;
    $('#import').dispatchEvent(new Event('change', {bubbles:true}));
  }
  chooseFile(csv);
  await waitFor(() => !$('#applyImport').disabled);
  assert(count() === 1, 'Reading a CSV should not change the address book before confirmation');
  assert($('#importBefore').textContent === '1' && $('#importAdded').textContent === '2' && $('#importAfter').textContent === '3', 'Import should show existing plus added totals');
  $('#importDialog [data-close]').click();
  assert(count() === 1, 'Cancelling import should preserve existing records');
  $('#openImport').click();
  chooseFile(csv);
  await waitFor(() => !$('#applyImport').disabled);
  $('#applyImport').click();
  assert(count() === 3 && !$('#importDialog').open, 'CSV and individual records should share one list');
  assert($('#list').textContent.includes('山田 太郎') && $('#list').textContent.includes('佐藤 花子'), 'CSV import should retain individual records');
  assert($('#printCount').textContent === '3', 'All additions should be available for print');
  $('#list .edit-button').click();
  form.elements.name.value = '山田 次郎';
  form.requestSubmit();
  assert(count() === 3 && $('#list').textContent.includes('山田 次郎'), 'Editing should update an existing recipient');
  $('#clearSelection').click();
  assert($('#print').disabled && $('#printCount').textContent === '0', 'Clear selection should disable print');
  $('#search').value = '佐藤';
  $('#search').dispatchEvent(new Event('input'));
  assert(count() === 1 && $('#selectAllLabel').textContent.includes('検索結果'), 'Search should narrow the displayed list');
  $('#selectAll').click();
  assert($('#printCount').textContent === '1', 'Select all while searching should only select matching recipients');
  $('#search').value = '';
  $('#search').dispatchEvent(new Event('input'));
  assert($('#selectAll').indeterminate && count() === 3, 'Partial selection should be reflected in the unified list');
  $('#list .person-button').click();
  $('#selectAll').click();
  let printCalled = false;
  window.print = () => { printCalled = true; };
  $('#print').click();
  assert(printCalled && $('#printArea').children.length === 3, 'Print should include selected individual and imported recipients');
  assert($('#preview').textContent.includes('山田 次郎'), 'Preview should match the selected row');
  await document.fonts.ready;
  return {ok:true, records:count(), selected:$('#printCount').textContent, checks:['individual registration', 'CSV preview and cancellation', 'unified address book', 'edit without duplication', 'filtered selection', 'batch print']};
})()
