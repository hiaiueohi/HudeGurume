const {app,BrowserWindow,ipcMain,shell}=require('electron');
const path=require('node:path');
const fs=require('node:fs');
const root=path.resolve(__dirname,'../.runtime');
fs.mkdirSync(root,{recursive:true});
const dataPath=fs.mkdtempSync(path.join(root,'ui-test-'));
app.setPath('userData',dataPath);
app.commandLine.appendSwitch('disk-cache-dir',path.join(dataPath,'cache'));
app.commandLine.appendSwitch('disable-gpu-shader-disk-cache');
const resultPath=path.join(root,'ui-test-result.json');
let win;
const timer=setTimeout(()=>{fs.writeFileSync(resultPath,JSON.stringify({ok:false,error:'Timed out'}));app.exit(1);},45000);
app.whenReady().then(async()=>{
  try{
    const store=require('../storage-ipc.cjs').registerStorage({ipcMain,shell,folder:path.join(dataPath,'Documents','宛名はがき'),getWindow:()=>win});
    require('../printing-ipc.cjs').registerPrinting({ipcMain,getWindow:()=>win});
    const legacy={records:[{id:'legacy',name:'移行確認 太郎',address:'東京都千代田区1-2'}],sender:{name:'差出人 花子'},offsetX:1,offsetY:-1};
    const seedWindow=new BrowserWindow({show:false,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}});
    await seedWindow.loadFile(path.resolve(__dirname,'../index.html'));
    await seedWindow.webContents.executeJavaScript("localStorage.setItem('atena-postcard-v1',"+JSON.stringify(JSON.stringify(legacy))+")");
    win=new BrowserWindow({show:false,width:1250,height:1000,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false,preload:path.resolve(__dirname,'../preload.cjs')}});
    const printerJobs=[];
    win.webContents.getPrintersAsync=async()=>[{name:'Test postcard printer',displayName:'テスト用プリンター',isDefault:true,status:0}];
    win.webContents.print=(options,callback)=>{printerJobs.push(options);callback(true);};
    seedWindow.close();
    await win.loadFile(path.resolve(__dirname,'../index.html'));
    const migrated=JSON.parse(fs.readFileSync(store.info.filePath,'utf8'));
    if(JSON.stringify(migrated)!==JSON.stringify(legacy))throw Error('Legacy renderer migration failed');
    const reset=await win.webContents.executeJavaScript("window.addressBookStorage.save({records:[],sender:{},offsetX:0,offsetY:0})");
    if(!reset.ok)throw Error('Test address book reset failed');
    await win.loadFile(path.resolve(__dirname,'../index.html'));
    await win.webContents.executeJavaScript('window.scrollTo(0,0); document.fonts.ready.then(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))');
    await new Promise(resolve=>setTimeout(resolve,150));
    await win.webContents.capturePage().then(img=>fs.writeFileSync(path.join(root,'ui-empty.png'),img.toPNG()));
    const result=await win.webContents.executeJavaScript(fs.readFileSync(path.join(__dirname,'ui-scenario.js'),'utf8'));
    const saved=JSON.parse(fs.readFileSync(store.info.filePath,'utf8'));
    if(saved.records.length!==3||!fs.existsSync(store.info.backupPath))throw Error('Native document save failed');
    await win.reload();
    await new Promise(resolve=>win.webContents.once('did-finish-load',resolve));
    const reloaded=await win.webContents.executeJavaScript("document.querySelectorAll('#list .entry').length");
    if(reloaded!==3)throw Error('Native reload failed');
    result.documentSave=true;
    result.frontEditing=await win.webContents.executeJavaScript(fs.readFileSync(path.join(__dirname,'front-scenario.js'),'utf8'));
    result.reload=true;
    result.legacyMigration=true;
    await win.webContents.executeJavaScript('window.scrollTo(0,0); new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    await new Promise(resolve=>setTimeout(resolve,150));
    await win.webContents.capturePage().then(img=>fs.writeFileSync(path.join(root,'ui-addressbook.png'),img.toPNG()));
    await win.webContents.executeJavaScript("document.querySelector('#openImport').click()");
    await win.webContents.executeJavaScript('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    await new Promise(resolve=>setTimeout(resolve,150));
    await win.webContents.capturePage().then(img=>fs.writeFileSync(path.join(root,'ui-import.png'),img.toPNG()));
    await win.webContents.executeJavaScript("document.querySelector('#importDialog').close()");
    result.designs=await win.webContents.executeJavaScript(fs.readFileSync(path.join(__dirname,'design-scenario.js'),'utf8'));
    if(printerJobs.length!==3||printerJobs[0].pageSize.width!==100000||printerJobs[0].pageSize.height!==148000||printerJobs[0].pageRanges[0].to!==0||printerJobs[1].pageRanges[0].to!==1)throw Error('Native print options mismatch');
    result.printing={nativeBridge:true,postcardSize:true,testOnePage:true,fullBatch:true,jobs:printerJobs.length};
    const typography=await win.webContents.executeJavaScript(fs.readFileSync(path.join(__dirname,'typography-scenario.js'),'utf8'));
    result.typography=typography.checks;
    fs.writeFileSync(path.join(root,'ui-vertical-export.png'),Buffer.from(typography.png.split(',')[1],'base64'));
    await win.webContents.capturePage().then(img=>fs.writeFileSync(path.join(root,'ui-vertical-design.png'),img.toPNG()));
    const pdfOptions={printBackground:true,preferCSSPageSize:true,displayHeaderFooter:false,margins:{top:0,bottom:0,left:0,right:0},pageSize:{width:100/25.4,height:148/25.4}};
    const checkPDF=(buffer,count)=>{const source=buffer.toString('latin1'),pages=[...source.matchAll(/\/Type\s*\/Page\b/g)];if(pages.length!==count)throw Error('Unexpected print page count: '+pages.length);const box=source.match(/\/MediaBox\s*\[\s*0\s+0\s+([\d.]+)\s+([\d.]+)/);if(!box||Math.abs(Number(box[1])-100*72/25.4)>1||Math.abs(Number(box[2])-148*72/25.4)>1)throw Error('Printed page must be 100 x 148 mm');};
    const backPDF=await win.webContents.printToPDF(pdfOptions);checkPDF(backPDF,2);fs.writeFileSync(path.join(root,'print-back-check.pdf'),backPDF);
    await win.webContents.executeJavaScript("document.querySelector('#addressTab').click();document.querySelector('#print').click()");
    await new Promise(resolve=>setTimeout(resolve,100));await win.webContents.executeJavaScript("document.querySelector('#printCancel').click()");
    const frontPDF=await win.webContents.printToPDF(pdfOptions);checkPDF(frontPDF,3);fs.writeFileSync(path.join(root,'print-front-check.pdf'),frontPDF);
    result.printing.pdfPageSize=true;result.printing.frontPages=3;result.printing.backPages=2;
    const pdfWindow=new BrowserWindow({show:false,width:900,height:1000,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}});
    await pdfWindow.loadFile(path.join(root,'print-back-check.pdf'));await new Promise(resolve=>setTimeout(resolve,900));
    await pdfWindow.webContents.capturePage().then(img=>fs.writeFileSync(path.join(root,'print-back-render.png'),img.toPNG()));
    await pdfWindow.loadFile(path.join(root,'print-front-check.pdf'));await new Promise(resolve=>setTimeout(resolve,900));
    await pdfWindow.webContents.capturePage().then(img=>fs.writeFileSync(path.join(root,'print-front-render.png'),img.toPNG()));pdfWindow.close();
    await win.webContents.executeJavaScript('postcardDesigns.saveProject('+JSON.stringify(typography.previous)+')');
    const designFolder=path.join(dataPath,'Documents','宛名はがき','年賀状デザイン','2027年_未（ひつじ）');
    const exports=fs.readdirSync(path.join(designFolder,'作成した年賀状'));
    if(exports.length!==1)throw Error('Expected one design PNG export');
    const imageData=fs.readFileSync(path.join(designFolder,'作成した年賀状',exports[0]));
    if(imageData.readUInt32BE(16)!==1200||imageData.readUInt32BE(20)!==1776)throw Error('Export size should match the postcard ratio');
    await win.loadFile(path.resolve(__dirname,'../index.html'));
    const restored=await win.webContents.executeJavaScript("document.querySelector('#designTab').click();({name:document.querySelector('#designName').textContent,message:document.querySelector('#designMessage').value})");
    if(restored.name!=='ふわふわの冬便り'||!restored.message.includes('笑顔あふれる'))throw Error('Design project reload failed');
    const restoredLayout=await win.webContents.executeJavaScript("postcardDesigns.loadProject().project.layout");
    if(restoredLayout.common.headline.x!==7||restoredLayout.common.headline.y!==6)throw Error('Layout reload failed');
    result.designs.reload=true;
    const frontReload=await win.webContents.executeJavaScript("addressBookStorage.load().state.frontLayout.common.names");
    if(frontReload.x!==-2||frontReload.writingMode!=='horizontal')throw Error('Front layout reload failed');result.frontEditing.reload=true;
    win.webContents.getPrintersAsync=async()=>[];
    await win.webContents.executeJavaScript(fs.readFileSync(path.join(__dirname,'printer-errors-scenario.js'),'utf8'));result.printing.noPrinters=true;
    win.webContents.getPrintersAsync=async()=>[{name:'Test postcard printer',isDefault:true}];
    win.webContents.print=(_options,callback)=>callback(false,'Invalid printer settings');
    await win.webContents.executeJavaScript("document.querySelector('#refreshPrinters').click()");
    await new Promise(resolve=>setTimeout(resolve,100));
    await win.webContents.executeJavaScript("document.querySelector('#printStart').click()");
    await new Promise(resolve=>setTimeout(resolve,100));
    const printFailure=await win.webContents.executeJavaScript("({error:document.querySelector('#printMessage').textContent,retry:!document.querySelector('#printStart').disabled})");
    if(!printFailure.error.includes('Invalid printer settings')||!printFailure.retry)throw Error('Print failure must be displayed and allow retry');result.printing.driverError=true;
    win.webContents.print=(options,callback)=>{printerJobs.push(options);callback(true);};
    await win.webContents.executeJavaScript("document.querySelector('#printCancel').click()");
    result.usability=await win.webContents.executeJavaScript(fs.readFileSync(path.join(__dirname,'usability-scenario.js'),'utf8'));
    await win.webContents.executeJavaScript('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');await new Promise(resolve=>setTimeout(resolve,150));
    await win.webContents.capturePage().then(img=>fs.writeFileSync(path.join(root,'ui-review.png'),img.toPNG()));
    await win.webContents.executeJavaScript("document.querySelector('#reviewPrint').click()");await new Promise(resolve=>setTimeout(resolve,150));
    await win.webContents.capturePage().then(img=>fs.writeFileSync(path.join(root,'ui-print-preview.png'),img.toPNG()));
    await win.webContents.executeJavaScript("document.querySelector('#printCancel').click();document.querySelector('#designTab').click()");
    await win.webContents.executeJavaScript('window.scrollTo(0,0); new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
    await new Promise(resolve=>setTimeout(resolve,200));
    await win.webContents.capturePage().then(img=>fs.writeFileSync(path.join(root,'ui-designs.png'),img.toPNG()));
    await win.webContents.executeJavaScript("document.querySelector('#openLayoutEditor').click()");
    await win.webContents.executeJavaScript('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
    await new Promise(resolve=>setTimeout(resolve,200));
    await win.webContents.capturePage().then(img=>fs.writeFileSync(path.join(root,'ui-layout-editor.png'),img.toPNG()));
    await win.webContents.executeJavaScript("document.querySelector('#layoutCancel').click()");
    fs.writeFileSync(resultPath,JSON.stringify(result,null,2));
    console.log(JSON.stringify(result));
    clearTimeout(timer);
    app.quit();
  }catch(error){
    const detail=win&&!win.isDestroyed()?await win.webContents.executeJavaScript("({status:document.querySelector('#status').textContent,dialog:document.querySelector('dialog[open]')?.textContent})").catch(()=>null):null;
    fs.writeFileSync(resultPath,JSON.stringify({ok:false,error:error.stack,detail},null,2));
    console.error(error);
    clearTimeout(timer);
    app.exit(1);
  }
});
